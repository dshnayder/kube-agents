#!/usr/bin/env python3
"""Does TimesFM beat the forecasts that cost nothing? Compare its 8-hour peak with three free
ones, on the dumps window.py wrote, and measure how much each series moves in a day.

    python3 baselines.py staging=data/staging.jsonl.gz:dump-staging7 \
        CI=data/series.jsonl.gz:dump-window7 > results/baselines.md

The free forecasts, each read from the series before the start time: the last hour's mean
repeated, the same hours yesterday, the same hours last week. A warning is about the peak, so
each method is scored by the highest hourly value it forecast in the window against the highest
that came, (P - V) / V: negative is a miss, positive an overshoot. The report gives the median
and the worst tenth on each side. Daily swing is (max - min) / mean of one calendar day's
hourly values.
"""

import gzip
import glob
import json
import os
import sys
from collections import defaultdict

import numpy as np

from backtest import DAY, HOUR
from pointwise import CLASSES, PERCENT, coarsen
from scope import included

WINDOW_HOURS = 8
WEEK = 7 * DAY
# Share of a day's hours that may be missing before the day is left out of the swing.
MAX_MISSING_DAY = 0.2
# A window "rises" when its peak is this far above the last hour's value.
RISE = 0.15
MISS, TYPICAL, OVERSHOOT = 10, 50, 90
ORIGIN_PREFIX = "origin-"
METHODS = ["TimesFM", "last hour repeated", "same hours yesterday", "same hours last week"]


def hourly(y):
    return coarsen(y[:len(y) // HOUR * HOUR], HOUR)


def load(path):
    series = (json.loads(line) for line in gzip.open(path, "rt"))
    return {s["id"]: np.array([np.nan if v is None else v for v in s["values"]], float)
            for s in series if included(s["id"])}


def swings(series, classes):
    out = defaultdict(list)
    for sid, y in series.items():
        h = hourly(y)
        for d in range(len(h) // 24):
            v = h[d * 24:(d + 1) * 24]
            if np.isnan(v).mean() > MAX_MISSING_DAY or np.nanmean(v) <= 0:
                continue
            out[classes[sid]].append((np.nanmax(v) - np.nanmin(v)) / np.nanmean(v))
    return out


def peaks(series, dump):
    """Per class and method, the relative peak error of every window; plus the rising windows."""
    err = defaultdict(lambda: defaultdict(list))
    rising = defaultdict(lambda: defaultdict(list))
    classes = {}
    for path in sorted(glob.glob(os.path.join(dump, ORIGIN_PREFIX + "*.npz"))):
        z = np.load(path)
        t = int(os.path.basename(path)[len(ORIGIN_PREFIX):].split(".")[0])
        for sid, cls, truth, pred in zip(z["ids"], z["classes"], z["truth"], z["pred"]):
            sid = str(sid)
            if sid not in series:
                continue
            classes[sid] = str(cls)
            y = series[sid]
            actual = hourly(truth)[:WINDOW_HOURS]
            if np.isnan(actual).any() or actual.max() <= 0:
                continue
            span = WINDOW_HOURS * HOUR
            forecast = {
                "TimesFM": np.nanmax(hourly(pred.astype(float))[:WINDOW_HOURS]),
                "last hour repeated": np.nanmean(y[t - HOUR:t]),
                "same hours yesterday": np.nanmax(hourly(y[t - DAY:t - DAY + span])),
                "same hours last week": np.nanmax(hourly(y[t - WEEK:t - WEEK + span])),
            }
            last = forecast["last hour repeated"]
            for method, p in forecast.items():
                if np.isnan(p):
                    continue
                e = p / actual.max() - 1
                err[str(cls)][method].append(e)
                if last > 0 and actual.max() / last - 1 > RISE:
                    rising[str(cls)][method].append(e)
    return err, rising, classes


def cell(v):
    if not v:
        return "-"
    m, lo, hi = (np.percentile(v, q) * PERCENT for q in (TYPICAL, MISS, OVERSHOOT))
    return f"{m:+.0f}% ({lo:+.0f}%, {hi:+.0f}%)"


def main():
    print("# TimesFM against free forecasts\n")
    print(f"Generated by `harness/baselines.py`. {WINDOW_HOURS}-hour windows from the window.py "
          "dumps, 7 days of history. Each cell is the forecast peak against the actual peak: "
          f"median (worst miss, worst overshoot in 1 window in {PERCENT // (PERCENT - OVERSHOOT)}).")
    for arg in sys.argv[1:]:
        name, paths = arg.split("=", 1)
        data, dump = paths.split(":", 1)
        series = load(data)
        err, rising, classes = peaks(series, dump)
        sw = swings({s: series[s] for s in classes}, classes)
        print(f"\n## {name}\n")
        print("| Series | Daily swing: typical | Daily swing: busy (1 in 10) | "
              + " | ".join(METHODS) + " |")
        print("|---" * (3 + len(METHODS)) + "|")
        for cls in CLASSES:
            if cls not in err:
                continue
            print(f"| {CLASSES[cls]} | {np.median(sw[cls]) * PERCENT:.0f}% | "
                  f"{np.percentile(sw[cls], OVERSHOOT) * PERCENT:.0f}% | "
                  + " | ".join(cell(err[cls][m]) for m in METHODS) + " |")
        print(f"\nWindows whose peak rose more than {RISE:.0%} above the last hour:\n")
        print("| Series | Rising windows | " + " | ".join(METHODS) + " |")
        print("|---" * (2 + len(METHODS)) + "|")
        for cls in CLASSES:
            if cls not in err:
                continue
            n = len(rising[cls]["TimesFM"])
            print(f"| {CLASSES[cls]} | {n}/{len(err[cls]['TimesFM'])} | "
                  + " | ".join(cell(rising[cls][m]) for m in METHODS) + " |")


if __name__ == "__main__":
    main()
