#!/usr/bin/env python3
"""How long a forecast takes: time one forecaster on forecasts of real series, by horizon,
batch size and history length.

    python3 timing.py --data series.jsonl.gz --forecaster http://localhost:8080 \
        > results/timing.md

Run it against an idle forecaster; another client sharing it inflates every figure. Each cell
repeats the request and reports the median, both as the server's own inference time and as the
wall time the client saw, which adds JSON encoding and the round trip.
"""

import argparse
import gzip
import json
import time

import numpy as np
import pandas as pd

from backtest import DAY, HOUR, fill, post

HORIZON_HOURS = (8, 24)
CONTEXT_DAYS = (1, 7, 28)
BATCH_SIZES = (1, 8, 64)
REPEATS = 5
# The first request after a start compiles the model's graph; it is not counted.
WARMUP = 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--forecaster", required=True)
    a = ap.parse_args()
    series = [json.loads(line) for line in gzip.open(a.data, "rt")]
    ys = [np.array([np.nan if v is None else v for v in s["values"]]) for s in series]
    rows = []
    for hours, days in ((h, d) for h in HORIZON_HOURS for d in CONTEXT_DAYS):
        # The most recent window of each series, skipping those too sparse to fill.
        inputs = [x for x in (fill(y[-days * DAY:]) for y in ys if len(y) >= days * DAY)
                  if x is not None]
        for size in BATCH_SIZES:
            if len(inputs) < size:
                continue
            batch = inputs[:size]
            server, wall = [], []
            for i in range(WARMUP + REPEATS):
                start = time.monotonic()
                _, secs, bucket = post(a.forecaster, batch, horizon=hours * HOUR)
                if i >= WARMUP:
                    server.append(secs)
                    wall.append(time.monotonic() - start)
            rows.append({"horizon": f"{hours} hours", "history": f"{days} days",
                         "series per request": size, "padded context": bucket,
                         "server seconds": f"{np.median(server):.2f}",
                         "wall seconds": f"{np.median(wall):.2f}",
                         "seconds per series": f"{np.median(wall) / size:.3f}"})
    print("# Forecast time\n")
    print(f"Generated by `harness/timing.py`. One forecaster, five-minute steps, median of "
          f"{REPEATS} requests after {WARMUP} warm-up.\n")
    print(pd.DataFrame(rows).set_index(["horizon", "history", "series per request"]).to_markdown())


if __name__ == "__main__":
    main()
